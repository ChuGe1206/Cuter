def _rust_sort_key(key: str) -> bytes:
    """按 Rust 里那条字符串的字节序排序（源码里的反斜杠 n 会被 Rust 解码成真新行）。"""
    return key.replace(chr(92) + "n", chr(10)).replace(chr(92) + '"', '"').encode("utf-8")


def main() -> int:
    write = "--write" in sys.argv
    keys_path = ROOT / "target" / "i18n-keys.json"
    keys = json.loads(keys_path.read_text(encoding="utf-8"))
    missing = [k for k in keys if k not in EN]
    unused = [k for k in EN if k not in keys]
    if missing:
        print(f"MISSING {len(missing)} translations:")
        for key in missing:
            print(f"  {key!r}")
    if unused:
        print(f"UNUSED {len(unused)} entries:")
        for key in unused:
            print(f"  {key!r}")
    if missing:
        return 1

    lines = []
    for key in sorted(EN, key=_rust_sort_key):
        value = EN[key].replace("\\", "\\\\").replace('"', '\\"')
        if "\\n" in EN[key]:
            # 键里的 \n 是源码字面量里的转义，生成时保持原样
            value = EN[key].replace('"', '\\"')
        escaped_key = key.replace('"', '\\"')
        lines.append(f'    ("{escaped_key}", "{value}"),')
    body = "\n".join(lines)
    print(f"entries: {len(EN)}")
    if write:
        target = ROOT / "crates" / "cuter-ui" / "src" / "i18n.table.rs"
        note = "// 由 tools/i18n/en_table.py --write 生成，不要手改；由 i18n.rs 用 include! 引进来。\n"
        target.write_text(f"{note}&[\n{body}\n]\n", encoding="utf-8")
        print(f"wrote {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
